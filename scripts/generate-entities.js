// Regenerates src/entities.js from the WHATWG named character reference table.
//   node scripts/generate-entities.js [path-or-url-of-entities.json]
// The default is https://html.spec.whatwg.org/entities.json. The output is
// committed; test/entities.test.js checks it against an independent decoder.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const source = process.argv[2] ?? 'https://html.spec.whatwg.org/entities.json';
const json = JSON.parse(/^https?:/.test(source) ? await (await fetch(source)).text() : await readFile(source, 'utf8'));

const named = []; // "name:hex[,hex]" for every "&name;"
const legacy = []; // names that also work without the semicolon ("&amp")
for (const [key, { codepoints }] of Object.entries(json)) {
  const name = key.slice(1);
  if (name.endsWith(';')) named.push(`${name.slice(0, -1)}:${codepoints.map((c) => c.toString(16)).join(',')}`);
  else legacy.push(name);
}
for (const name of legacy) {
  if (!json[`&${name};`] || json[`&${name};`].characters !== json[`&${name}`].characters) throw new Error(`legacy &${name} differs from &${name};`);
}

const wrap = (items, sep) => items.join(sep).replace(/(.{100,}?)\|/g, '$1|\n  ');
const out = `// Generated by scripts/generate-entities.js from the WHATWG named character reference table
// (https://html.spec.whatwg.org/entities.json). Do not edit; regenerate instead.
// NAMED: "name:codepoint[,codepoint]" entries, separated by "|", for every "&name;".
// LEGACY: the names that are also recognised without the closing ";" ("&amp", "&eacute").

const NAMED = \`
  ${wrap(named, '|')}\`;

const LEGACY = '${legacy.join(' ')}';

/** "&name;" names (without the ";") → their characters. */
export const ENTITIES = new Map(NAMED.trim().split('|').map((entry) => {
  const [name, hex] = entry.trim().split(':');
  return [name, String.fromCodePoint(...hex.split(',').map((h) => parseInt(h, 16)))];
}));

/** Names that may also be written without the ";" (a historical quirk, spec-defined). */
export const LEGACY_ENTITIES = new Set(LEGACY.split(' '));
`;
await writeFile(fileURLToPath(new URL('../src/entities.js', import.meta.url)), out);
console.log(`src/entities.js: ${named.length} names, ${legacy.length} legacy`);
